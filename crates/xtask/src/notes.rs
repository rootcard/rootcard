//! The text of a GitHub release (`cargo run -p xtask -- release-notes`, docs/RELEASING.md §4).
//!
//! The release workflow writes the notes from the four changelogs' sections for the version, the release files listed
//! in `SHA256SUMS` and how to verify them. A release the owner made by hand, with or without text of their own, gets the
//! generated block ahead of that text; a later run replaces only the block, so the owner's text is never lost.

/// The repository whose workflow signs the release files (`gh attestation verify --repo`).
pub const REPOSITORY: &str = "rootcard/rootcard";

/// The line that starts the generated block. Text before it or after [`END`] belongs to whoever wrote the release.
pub const START: &str = "<!-- release-notes: generated by .github/workflows/release.yml from the changelogs; text below the end mark is kept -->";
/// The line that ends the generated block.
pub const END: &str = "<!-- release-notes: end -->";

/// The platforms the key tool is built for in the release workflow: Rust target and how the notes name it.
pub const TARGETS: [(&str, &str); 5] = [
    ("x86_64-unknown-linux-musl", "Linux, x86_64 (static)"),
    ("aarch64-unknown-linux-musl", "Linux, arm64 (static)"),
    ("aarch64-apple-darwin", "macOS, Apple silicon"),
    ("x86_64-apple-darwin", "macOS, Intel"),
    ("x86_64-pc-windows-msvc", "Windows, x86_64"),
];

/// The section of `changelog` for `version`: the lines between its `## <version>` heading and the next `## ` heading,
/// without leading and trailing blank lines. `None` if there is no such heading.
pub fn changelog_section(changelog: &str, version: &str) -> Option<String> {
    let mut lines = changelog.lines();
    lines.find(|line| {
        line.strip_prefix("## ")
            .and_then(|rest| rest.strip_prefix(version))
            .is_some_and(|rest| rest.is_empty() || rest.starts_with(' '))
    })?;
    let body: Vec<&str> = lines.take_while(|line| !line.starts_with("## ")).collect();
    Some(body.join("\n").trim_matches('\n').trim_end().to_string())
}

/// What a release file is, from its name, for the download table. `None` for a file the notes do not know.
fn describe(file: &str, version: &str) -> Option<String> {
    if file == format!("rootcard-keytool-{version}.html") {
        return Some("Key tool page: open it from your own disk (`file://`), never from a host".to_string());
    }
    if file == format!("rootcard-{version}.tgz") {
        return Some(format!(
            "npm package [`rootcard@{version}`](https://www.npmjs.com/package/rootcard/v/{version}), as npm serves it"
        ));
    }
    if let Some(name) = file.strip_suffix(&format!("-{version}.crate")) {
        return Some(format!(
            "Crate [`{name}`](https://crates.io/crates/{name}/{version}), as crates.io serves it"
        ));
    }
    let rest = file.strip_prefix(&format!("rootcard-cli-{version}-"))?;
    let target = rest.strip_suffix(".tar.gz").or_else(|| rest.strip_suffix(".zip"))?;
    let (_, platform) = TARGETS.iter().find(|(t, _)| *t == target)?;
    Some(format!("Key tool `rootcard`, {platform}"))
}

/// The file names of a `SHA256SUMS` file (`<64 hex>  <name>` per line, `*<name>` in binary mode).
fn sum_files(sums: &str) -> Result<Vec<String>, String> {
    let mut files = Vec::new();
    for line in sums.lines().filter(|l| !l.trim().is_empty()) {
        let (hash, name) = line
            .split_once(' ')
            .ok_or_else(|| format!("SHA256SUMS: not `<hash>  <file>`: {line:?}"))?;
        if hash.len() != 64 || !hash.bytes().all(|b| b.is_ascii_hexdigit()) {
            return Err(format!("SHA256SUMS: not a SHA-256 hash: {hash:?}"));
        }
        let name = name.trim_start_matches(' ').trim_start_matches('*');
        if name.is_empty() || name.contains('/') || name.contains('`') {
            return Err(format!("SHA256SUMS: unexpected file name {name:?}"));
        }
        files.push(name.to_string());
    }
    if files.is_empty() {
        return Err("SHA256SUMS lists no files".to_string());
    }
    Ok(files)
}

/// The generated block of the notes, from [`START`] to [`END`]. `sections` are each released package's name and its
/// changelog section for `version`; `sums` is the release's `SHA256SUMS`.
pub fn release_notes(version: &str, sections: &[(&str, String)], sums: &str) -> Result<String, String> {
    let files = sum_files(sums)?;
    let mut out = vec![START.to_string(), "## What changed".to_string(), String::new()];
    let unchanged: Vec<&str> = sections
        .iter()
        .filter(|(_, s)| s.is_empty() || s == "No changes.")
        .map(|(name, _)| *name)
        .collect();
    for (name, section) in sections.iter().filter(|(name, _)| !unchanged.contains(name)) {
        out.push(format!("### {name}"));
        out.push(String::new());
        out.push(section.clone());
        out.push(String::new());
    }
    if !unchanged.is_empty() {
        out.push(format!("No changes in {}.", unchanged.join(", ")));
        out.push(String::new());
    }

    out.push("## Downloads".to_string());
    out.push(String::new());
    out.push("| File | What |".to_string());
    out.push("|---|---|".to_string());
    for file in &files {
        let what = describe(file, version).ok_or_else(|| format!("SHA256SUMS: no description for {file:?}"))?;
        out.push(format!("| `{file}` | {what} |"));
    }
    out.push(format!(
        "| `rootcard-{version}.sigstore.json` | The signature of every file above, as a Sigstore bundle |"
    ));
    out.push(String::new());
    out.push(format!(
        "The key tool is also `cargo install rootcard-cli --version {version} --locked`. How to install it and run a \
         host: [docs/HOSTING.md](https://github.com/{REPOSITORY}/blob/v{version}/docs/HOSTING.md)."
    ));
    out.push(String::new());

    let example = files
        .iter()
        .find(|f| f.starts_with("rootcard-cli-") && f.ends_with(".tar.gz"))
        .unwrap_or(&files[0]);
    out.push("## Verifying a download".to_string());
    out.push(String::new());
    out.push(format!(
        "Every file is signed by the release workflow of `{REPOSITORY}`, with GitHub artifact attestations (Sigstore \
         build provenance): the signature says which workflow run built the file, from which commit of tag \
         `v{version}`. Check the signature and the checksum before you run the key tool or open the page:"
    ));
    out.push(String::new());
    out.push("```sh".to_string());
    out.push(format!("gh attestation verify {example} --repo {REPOSITORY}"));
    out.push(
        "sha256sum -c SHA256SUMS --ignore-missing     # macOS: shasum -a 256 -c SHA256SUMS --ignore-missing"
            .to_string(),
    );
    out.push("```".to_string());
    out.push(String::new());
    out.push(format!(
        "Without the GitHub API, `gh attestation verify <file> --repo {REPOSITORY} --bundle \
         rootcard-{version}.sigstore.json` checks the same signature. The crates and the npm package are checked by the workflow to be byte for byte what the registries serve; \
         npm also shows its own provenance (`npm audit signatures`)."
    ));
    out.push(String::new());

    out.push("## Checksums (SHA-256)".to_string());
    out.push(String::new());
    out.push("```".to_string());
    out.push(sums.trim_end().to_string());
    out.push("```".to_string());
    out.push(END.to_string());
    Ok(out.join("\n") + "\n")
}

/// The notes of a release that already has the text `earlier`: the generated block first, then `earlier` without any
/// block an earlier run generated. Text the owner wrote, before or after such a block, is kept in its order.
pub fn merge(generated: &str, earlier: &str) -> String {
    let earlier = earlier.replace("\r\n", "\n");
    let kept = match (earlier.find(START), earlier.find(END)) {
        (Some(start), Some(end)) if start < end => {
            let (before, after) = (earlier[..start].trim(), earlier[end + END.len()..].trim());
            [before, after]
                .iter()
                .filter(|s| !s.is_empty())
                .copied()
                .collect::<Vec<_>>()
                .join("\n\n")
        }
        _ => earlier,
    };
    let kept = kept.trim();
    if kept.is_empty() {
        generated.to_string()
    } else {
        format!("{generated}\n{kept}\n")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const SUMS: &str = "\
1111111111111111111111111111111111111111111111111111111111111111  rootcard-0.4.0.crate
2222222222222222222222222222222222222222222222222222222222222222  rootcard-0.4.0.tgz
3333333333333333333333333333333333333333333333333333333333333333  rootcard-cli-0.4.0-aarch64-apple-darwin.tar.gz
4444444444444444444444444444444444444444444444444444444444444444  rootcard-cli-0.4.0-x86_64-pc-windows-msvc.zip
5555555555555555555555555555555555555555555555555555555555555555  rootcard-cli-0.4.0-x86_64-unknown-linux-musl.tar.gz
6666666666666666666666666666666666666666666666666666666666666666  rootcard-host-0.4.0.crate
7777777777777777777777777777777777777777777777777777777777777777  rootcard-keytool-0.4.0.html
";

    #[test]
    fn sections() {
        let log = "# Changelog\n\n## Unreleased\n\n## 0.4.0 - 2026-11-21\n\n- One.\n  More.\n\n- Two.\n\n\
                   ## 0.4.0-rc.1 - 2026-11-20\n\nNo changes.\n\n## 0.3.5\n\n- Old.\n";
        assert_eq!(
            changelog_section(log, "0.4.0").as_deref(),
            Some("- One.\n  More.\n\n- Two.")
        );
        assert_eq!(changelog_section(log, "0.4.0-rc.1").as_deref(), Some("No changes."));
        assert_eq!(changelog_section(log, "0.3.5").as_deref(), Some("- Old."));
        assert_eq!(changelog_section(log, "Unreleased").as_deref(), Some(""));
        assert_eq!(changelog_section(log, "0.4"), None);
        assert_eq!(changelog_section(log, "0.5.0"), None);
    }

    #[test]
    fn notes() {
        let sections = [
            ("rootcard (crate)", "- A change.".to_string()),
            ("rootcard-host (crate)", "No changes.".to_string()),
            ("rootcard-cli (crate)", "- Another.".to_string()),
            ("rootcard (npm)", "No changes.".to_string()),
        ];
        let notes = release_notes("0.4.0", &sections, SUMS).unwrap();
        assert!(notes.starts_with(START) && notes.ends_with(&format!("{END}\n")));
        assert!(notes.contains("### rootcard (crate)\n\n- A change.\n"));
        assert!(notes.contains("### rootcard-cli (crate)\n\n- Another.\n"));
        assert!(notes.contains("No changes in rootcard-host (crate), rootcard (npm)."));
        assert!(!notes.contains("### rootcard-host"));
        assert!(notes.contains("| `rootcard-cli-0.4.0-x86_64-pc-windows-msvc.zip` | Key tool `rootcard`, Windows"));
        assert!(notes.contains("| `rootcard-host-0.4.0.crate` | Crate [`rootcard-host`]"));
        assert!(notes.contains("| `rootcard-0.4.0.crate` | Crate [`rootcard`]"));
        assert!(notes.contains("| `rootcard-0.4.0.tgz` | npm package"));
        assert!(notes.contains("| `rootcard-keytool-0.4.0.html` | Key tool page"));
        assert!(notes.contains("gh attestation verify rootcard-cli-0.4.0-aarch64-apple-darwin.tar.gz --repo"));
        assert!(notes.contains(SUMS.trim_end()));
        assert_eq!(notes.matches(START).count(), 1);
    }

    #[test]
    fn notes_refuse_unknown_files_and_bad_sums() {
        let sections = [("rootcard (crate)", "- A change.".to_string())];
        for bad in [
            "",
            "1111  rootcard-0.4.0.crate\n",
            "1111111111111111111111111111111111111111111111111111111111111111  other.bin\n",
            "1111111111111111111111111111111111111111111111111111111111111111  rootcard-0.3.0.crate\n",
            "1111111111111111111111111111111111111111111111111111111111111111  rootcard-cli-0.4.0-riscv64.tar.gz\n",
            "1111111111111111111111111111111111111111111111111111111111111111  dir/rootcard-0.4.0.crate\n",
        ] {
            assert!(release_notes("0.4.0", &sections, bad).is_err(), "{bad:?}");
        }
        let binary_mode = "1111111111111111111111111111111111111111111111111111111111111111 *rootcard-0.4.0.crate\n";
        assert!(release_notes("0.4.0", &sections, binary_mode).is_ok());
    }

    #[test]
    fn merging_keeps_the_owners_text() {
        let first = format!("{START}\nfirst\n{END}\n");
        let second = format!("{START}\nsecond\n{END}\n");
        // An empty release (made by hand without text) gets the notes alone.
        assert_eq!(merge(&first, ""), first);
        assert_eq!(merge(&first, " \r\n"), first);
        // Text written by hand goes after the notes.
        let owner = "Highlights: the key tool ships as binaries.\r\n";
        let once = merge(&first, owner);
        assert_eq!(once, format!("{first}\nHighlights: the key tool ships as binaries.\n"));
        // A second run replaces its own block and keeps the owner's text, also text around the block.
        assert_eq!(
            merge(&second, &once),
            format!("{second}\nHighlights: the key tool ships as binaries.\n")
        );
        let around = format!("Before.\n{first}After.\n");
        assert_eq!(merge(&second, &around), format!("{second}\nBefore.\n\nAfter.\n"));
        // A run on its own earlier notes changes nothing.
        assert_eq!(merge(&first, &first), first);
    }
}
